#!/usr/bin/env python3
"""Generate src/emunah/mapper/lines.lua -- the IRE Mudlet Mapper's locator lines, as data.

The user chose (2026-10-12) to take the mapper's game lines from mmp's own trigger set,
the way EmunahTriggers.xml takes affliction lines from the reference system: verbatim, regenerated by a tool,
never hand-edited. mmp is the reference for these lines by the user's ruling.

WHY A LUA DATA FILE AND NOT A TRIGGER PACKAGE
---------------------------------------------
mapper/locate.lua registers a trigger only for the locators switched on (`map.locators`), so
a Priest does not carry a Druid's Forestwatch line. A Mudlet package would load every
trigger whether wanted or not, and would be one more thing to install.

WHAT IS TAKEN
-------------
Each entry below names an mmp trigger and says what its captures are: the PATTERN is copied
from mmp's XML, the MEANING is declared here, because mmp's scripts call mmp's own
functions (locateAndEcho and friends) and are not something to translate mechanically. A
trigger mmp no longer has, or whose pattern no longer has the captures declared, fails the
build rather than shipping a pattern that cannot fire.

Kinds (what mapper/locate.lua does with a match):
    person   a person at a named room                   captures: person, room[, area]
    near     a person entering a room next to you       captures: person, room, dir
    angel    the angel's presence scan, or its sense     captures: person, room / room
    with     " is with X." after an angel sense          captures: person
    place    a named room, no person (shrines)           captures: room
    shop     a shop directory row: the room name at column 48 of the line
    who      a WHO B row: a person and their room         captures: person, room

Usage:
    python3 tools/build-mapper-lines.py [mudlet-mapper.xml] [output]

The XML defaults to the copy in the Achaea profile; output to src/emunah/mapper/lines.lua.
"""
import pathlib
import re
import sys
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parent.parent
DEFAULT_XML = pathlib.Path.home() / ".config/mudlet/profiles/Achaea/map downloads/mudlet-mapper.xml"
DEFAULT_OUT = ROOT / "src" / "emunah" / "mapper" / "lines.lua"

# (key, group, kind, mmp trigger path, captures). The path is the trigger's name, then its
# child's name when the pattern lives on a child. Captures map a role to the capture group
# number in the pattern (1 = the first group).
ENTRIES = [
    ("farsee",        "farsee",    "person", ["Farsee initial", "Local farsee"], {"person": 1, "room": 2}),
    ("farsee.veil",   "farsee",    "person", ["Farsee initial", "Veil farsee"], {"person": 1, "room": 2, "area": 3}),
    ("view",          "view",      "person", ["View"], {"person": 1, "room": 2}),
    ("mindsense",     "mindsense", "person", ["Mindsense"], {"person": 1, "room": 2}),
    ("allsight",      "allsight",  "person", ["Allsight"], {"person": 1, "room": 2}),
    ("alertness",     "alertness", "near",   ["Alertness (Achaea+Imperian)"], {"person": 1, "room": 2, "dir": 3}),
    ("angel.scan",    "angel",     "angel",  ["Angel/Demon presences", "Each person"], {"person": 1, "room": 2}),
    ("angel.sense",   "angel",     "angel",  ["Angel sense"], {"room": 1}),
    ("angel.with",    "angel",     "with",   ["Angel sense", "Each person"], {"person": 1}),
    ("angel.trace",   "angel",     "person", ["Angel trace"], {"person": 1, "room": 2}),
    ("shrine.defile", "shrines",   "place",  ["Defilement"], {"room": 1}),
    ("shrine.down",   "shrines",   "place",  ["Defiled"], {"room": 1}),
    ("shrine.log",    "shrines",   "place",  ["Downed shrine in Order logs"], {"room": 1}),
    ("shop",          "shop",      "shop",   ["Directory - Catch shop entry"], {}),
    ("who",           "who",       "who",    ["Achaea", "Parse wholist"], {"person": 1, "room": 2}),
]

# THE MOVEMENT LINES: what the game says when a step does not simply happen. Every pattern
# of each trigger is taken, of any Mudlet type, and turned into a regex (exact -> ^...$,
# begin-of-line -> ^..., substring -> as is). What each means for a walk, from mmp's script
# for it, is declared here; mapper/moves.lua does it.
#   swim     water ahead: SWIM <dir> (mmp.swim)
#   open     a closed door: OPEN DOOR <dir>, then the step (mmp.openDoor)
#   unlock   a locked door: UNLOCK DOOR <dir>, then the step (mmp.unlockDoor)
#   refused  this way is shut to us -- slammed, bolted, keyless, a wall (mmp.failpath);
#            ours locks the exit for the session and plans around it
#   slow     the move takes longer; wait `seconds` more for it (mmp.customwalkdelay)
#   hasty    moved too fast: the step was not taken, send it again
#   noworm   "There is no wormhole here." on a worm warp step
#   land     flying, and the way is indoors (mmp lands only in Starmourn)
MOVES = [
    ("swim",            "swim",    ["Have to swim"], None),
    ("door.closed",     "open",    ["Door in the way"], None),
    ("door.locked",     "unlock",  ["Door Locked"], None),
    ("door.cannot",     "refused", ["Failed to open door"], None),
    ("door.piety",      "refused", ["Doors", "Closing doors", "Lack of piety"], None),
    ("door.slam",       "refused", ["Doors", "Closing doors", "Slam Shut"], None),
    ("door.denied",     "refused", ["Doors", "Closing doors", "Denied entry"], None),
    ("door.cij",        "refused", ["Doors", "Closing doors", "CIJ"], None),
    ("door.springs",    "refused", ["Doors", "Closing doors", "Springs back"], None),
    ("door.bolted",     "refused", ["Doors", "Closing doors", "Bolted"], None),
    ("door.selfclose",  "refused", ["Doors", "Closing doors", "Self-closing door"], None),
    ("door.click",      "refused", ["Door closed"], None),
    ("wall",            "refused", ["Wall"], None),
    ("slow.rubble",     "slow",    ["Rubble at the exit"], 2),
    ("slow.hobble",     "slow",    ["Hobbling"], 2),
    ("slow.frozen",     "slow",    ["Frozen"], 2),
    ("slow.sluggish",   "slow",    ["Retardation/aeon walk delay"], 2),
    ("slow.wormhole",   "slow",    ["Wormhole"], 4),
    ("slow.descent",    "slow",    ["Flying", "Wait for landing"], 4),
    ("hasty",           "hasty",   ["Too quick"], None),
    ("noworm",          "noworm",  ["No wormhole"], None),
    ("land",            "land",    ["Flying", "move indoors failed by flying"], None),
]

TYPE_TO_REGEX = {"0": "substring", "1": "regex", "2": "begin", "3": "exact"}


def as_regex(pattern, kind):
    if kind == "regex":
        return pattern
    escaped = re.sub(r"([\\^$.|?*+()\[\]{}])", r"\\\1", pattern)
    if kind == "exact":
        return "^" + escaped + "$"
    if kind == "begin":
        return "^" + escaped
    return escaped


# Lines that open or close a window rather than locate anyone. Verbatim from mmp.
SCAN_OPENERS = ["Angel/Demon presences"]


def children(node, name):
    return [c for c in node.findall("Trigger") + node.findall("TriggerGroup") if c.findtext("name") == name]


def find(root, path):
    """The trigger at a name path, searching anywhere for the first name."""
    first = [t for t in root.iter() if t.tag in ("Trigger", "TriggerGroup") and t.findtext("name") == path[0]]
    found = []
    for node in first:
        current = [node]
        for name in path[1:]:
            current = [c for n in current for c in children(n, name)]
        found.extend(current)
    return found


def regexes(trigger):
    patterns = [p.text for p in trigger.findall("regexCodeList/string")]
    types = [p.text for p in trigger.findall("regexCodePropertyList/integer")]
    # Type 1 is a Perl regex; 0/2/3 substring, begin-of-line and exact -- the cheap
    # pre-filters mmp puts ahead of the regex in a multi-line trigger.
    return [p for p, t in zip(patterns, types) if t == "1" and p]


def groups(pattern):
    """Capturing groups in a PCRE pattern: '(' not escaped and not '(?'."""
    return len(re.findall(r"(?<!\\)\((?!\?)", pattern))


def literal(text):
    for level in range(0, 5):
        eq = "=" * level
        if f"]{eq}]" not in text and not text.endswith("]" + eq):
            return f"[{eq}[{text}]{eq}]"
    raise ValueError("cannot quote " + text)


def main():
    source = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_XML
    out = pathlib.Path(sys.argv[2]) if len(sys.argv) > 2 else DEFAULT_OUT
    root = ET.parse(source).getroot()
    version = "?"
    for script in root.iter("Script"):
        m = re.search(r'local newversion = "([^"]+)"', script.findtext("script") or "")
        if m:
            version = m.group(1)

    lines = []
    problems = []
    for key, group, kind, path, captures in ENTRIES:
        found = find(root, path)
        if len(found) != 1:
            problems.append(f"{key}: {' / '.join(path)} found {len(found)} times in mmp")
            continue
        patterns = regexes(found[0])
        if not patterns and kind == "shop":
            patterns = [p.text for p in found[0].findall("regexCodeList/string")]
        if not patterns:
            problems.append(f"{key}: no regex on {' / '.join(path)}")
            continue
        for index, pattern in enumerate(patterns):
            need = max(captures.values()) if captures else 0
            if groups(pattern) < need:
                problems.append(f"{key}: {pattern!r} has {groups(pattern)} groups, needs {need}")
                continue
            fields = [f'key = "{key}"', f'group = "{group}"', f'kind = "{kind}"',
                      f'pattern = {literal(pattern)}',
                      f'source = "{" / ".join(path)}"']
            if kind == "shop":
                # mmp finds the shop's room name with a child trigger on the same line,
                # `^.{47} (.+)$`: the name starts after column 48. Read from mmp, not assumed.
                child = children(found[0], "Make shop name clickable")
                width = None
                if len(child) == 1:
                    for p in child[0].findall("regexCodeList/string"):
                        m = re.match(r"^\^\.\{(\d+)\} \(\.\+\)\$$", p.text or "")
                        if m:
                            width = int(m.group(1)) + 1
                if not width:
                    problems.append("shop: mmp's 'Make shop name clickable' column not found")
                    continue
                fields.append(f"column = {width}")
            for role, number in sorted(captures.items()):
                fields.append(f"{role} = {number}")
            lines.append("   { " + ", ".join(fields) + " },")

    openers = []
    for name in SCAN_OPENERS:
        found = find(root, [name])
        if len(found) != 1:
            problems.append(f"opener {name} found {len(found)} times")
            continue
        openers.extend(p.text for p in found[0].findall("regexCodeList/string") if p.text)

    moves = []
    for key, kind, path, seconds in MOVES:
        found = find(root, path)
        if len(found) != 1:
            problems.append(f"{key}: {' / '.join(path)} found {len(found)} times in mmp")
            continue
        patterns = [p.text for p in found[0].findall("regexCodeList/string")]
        types = [p.text for p in found[0].findall("regexCodePropertyList/integer")]
        # A multi-line trigger fires on its conditions in sequence: "You open the door to
        # the" arms Door closed, and only the regex after it ("closes with a click") is the
        # refusal. Taking every pattern made opening a door read as being refused. So from a
        # multi-line trigger only the regexes are taken.
        multiline = found[0].get("isMultiline") == "yes"
        taken = 0
        for pattern, ptype in zip(patterns, types):
            how = TYPE_TO_REGEX.get(ptype)
            if not how or not pattern:
                continue   # a prompt-line or Lua-function pattern: context, not a line
            if multiline and how != "regex":
                continue
            fields = [f'key = "{key}"', f'kind = "{kind}"',
                      f'pattern = {literal(as_regex(pattern, how))}',
                      f'source = "{" / ".join(path)}"']
            if seconds:
                fields.append(f"seconds = {seconds}")
            moves.append("   { " + ", ".join(fields) + " },")
            taken += 1
        if taken == 0:
            problems.append(f"{key}: no usable pattern on {' / '.join(path)}")

    if problems:
        for problem in problems:
            print("error:", problem, file=sys.stderr)
        sys.exit(1)

    body = "\n".join(lines)
    moves_body = "\n".join(moves)
    scan = "\n".join(f"   {literal(p)}," for p in openers)
    out.write_text(f"""--- GENERATED by tools/build-mapper-lines.py from the IRE Mudlet Mapper {version}. Do not edit:
--- change the generator and run it again.
---
--- mmp's locator lines, verbatim [mmp]. Each pattern is copied from mmp's XML; what its
--- captures mean (person, room, area, direction) is declared in the generator, since mmp's
--- own scripts call mmp's functions. mapper/locate.lua registers only the groups switched on
--- in `map.locators`; mapper/moves.lua acts on the movement lines.

local M = {{}}

M.VERSION = "{version}"

M.LINES = {{
{body}
}}

--- What the game says when a step does not simply happen [mmp]. Mudlet's exact,
--- begin-of-line and substring patterns are written here as regexes.
M.MOVES = {{
{moves_body}
}}

--- Exact lines that start the angel's presence scan; until the prompt, "Your guardian angel
--- senses" lines are the scan's, not a sense of one person (mmp disables Angel sense for it).
M.SCAN_OPENERS = {{
{scan}
}}

return M
""")
    print(f"wrote {out}: {len(lines)} locator lines and {len(moves)} movement lines from mmp {version}")


if __name__ == "__main__":
    main()
